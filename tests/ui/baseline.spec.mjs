import { test, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
test.skip(process.env.BASELINE !== '1', 'Baseline only, run on the original application');
test('baseline submission, completed lock, Coaches redirect and dashboard', async ({page,context},info) => {
  await context.route('**/*', route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
  await page.goto('/');
  await page.getByRole('link',{name:'Coaches ›',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Coach login'})).toBeVisible();
  await page.goto('/#today');
  await page.getByRole('button',{name:'U18'}).click();
  await page.getByLabel('Four digit U18 code').fill('2468');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('button',{name:'Test Marlins'}).click();
  await page.getByRole('button',{name:'Alex'}).click();
  await page.getByRole('button',{name:'Start session',exact:true}).click();
  await expect(page.locator('[data-set-row]')).toHaveCount(6);
  await page.locator('[data-set-input]').first().fill('65');
  await page.locator('[data-field="duration_seconds"]').first().fill('4.2');
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  const before=(await (await page.request.get('/__test/metrics')).json()).length;
  const started=performance.now();
  await page.getByRole('button',{name:'Finish session',exact:true}).click();
  await expect(page.getByRole('button',{name:'Complete session',exact:true})).toBeVisible();
  const modalMs=performance.now()-started;
  await page.getByRole('button',{name:'Complete session',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Great work.'})).toBeVisible();
  const successMs=performance.now()-started;
  const requests=(await (await page.request.get('/__test/metrics')).json()).slice(before);
  const writes=requests.filter(r=>r.method==='POST');
  await expect(page.locator('[data-set-input]').first()).toBeDisabled();
  await page.reload();
  await expect(page.locator('[data-set-input]').first()).toHaveValue('65');
  await mkdir('docs/test-evidence',{recursive:true});
  await page.screenshot({path:'docs/test-evidence/baseline-completed.png',fullPage:true});
  await page.goto('/#coach/login');
  await page.getByLabel('Email').fill('admin@example.test');
  await page.getByLabel('Password',{exact:true}).fill('test-only-password');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Today',exact:true})).toBeVisible();
  await expect(page.locator('.calendar-grid')).toHaveCount(0);
  const result={environment:'Loopback Chrome + PGlite; synthetic Auth/REST adapter, not hosted staging',sets:6,exercises:2,injectedWriteLatencyMs:80,finishToModalMs:modalMs,finishToSuccessMs:successMs,writeRequests:writes.length,writeResponseMs:writes.map(r=>r.ms),coachesRedirect:true,completedEditing:false,dashboardCalendar:false};
  await writeFile('docs/test-evidence/baseline-performance.json',JSON.stringify(result,null,2)+'\n');
  await info.attach('baseline',{body:JSON.stringify(result),contentType:'application/json'});
});
